SAFE_REFUSAL = "Maaf, saya tidak dapat memenuhi permintaan untuk mengubah aturan atau mengungkap informasi internal."
FOLLOW_UP = re.compile(
    r"^(kalau|bagaimana dengan|lalu|dan untuk|yang tadi|itu|terus|untuk yang|masa sih|yakin|benarkah|"
    r"apa benar|bukankah|bukannya|lah|kan|eror|error|coba (?:cek|periksa)|periksa (?:lagi|ulang))\b",
    re.I,
)
FOLLOW_UP_REFERENCE = re.compile(r"\b(?:itu|tadi|tersebut|sebelumnya)\b", re.I)
# Source markers: [S1], also lists/ranges the model sometimes writes: [S1, S3], [S1–S10].
CITATION = re.compile(r"\s*\[S\d+(?:\s*(?:,|;|-|–|—|dan)\s*S\d+)*\]")


def cited_ids(answer, valid=None):
    """IDs cited by an answer. A range ([S1–S10]) is shorthand, so it only covers existing sources."""
    ids = set()
    for marker in CITATION.findall(answer):
        numbers = [int(n) for n in re.findall(r"S(\d+)", marker)]
        if len(numbers) == 2 and re.search(r"[-–—]", marker):
            span = {f"S{n}" for n in range(min(numbers), max(numbers) + 1)}
            ids.update(span & valid if valid is not None else span)
        else:
            ids.update(f"S{n}" for n in numbers)
    return ids


# A sentence stating that information is absent from the documents, e.g.
# "... belum ditemukan dalam dokumen yang tersedia" or "Pengumuman tidak mencantumkan tanggal ...".
# Explanatory wording such as "lulusan SMA tidak disebut khusus pada butir tersebut" is not one.
SOURCE_WORDS = r"(?:dokumen|sumber|knowledge base|pengumuman|peraturan|perpol|jadwal)"
NOT_FOUND_CLAUSE = (
    r"\b(?:belum|tidak)\s+(?:ditemukan|tercantum|tersedia|disebutkan|dicantumkan|termuat|dimuat)\b"
    r"[^.!?\n]{0,60}?\b(?:dalam|pada|di)\s+(?:\w+\s+){0,3}?" + SOURCE_WORDS + r"\b"
)
# Pure "not found in the documents" sentence: cites nothing, so its markers can be dropped.
ABSTAIN_SENTENCE = re.compile(NOT_FOUND_CLAUSE, re.I)
# Any statement that the documents lack something: worth one broader search.
ABSENCE_STATEMENT = re.compile(
    NOT_FOUND_CLAUSE
    + r"|\b"
    + SOURCE_WORDS
    + r"\b[^.!?\n]{0,80}?\b(?:belum|tidak)\s+(?:mencantumkan|menyebutkan|memuat|mengatur)\b",
    re.I,
)
COURTESY_SENTENCE = re.compile(r"^(?:silakan|mohon|anda dapat|untuk kepastian)\b", re.I)


def sentences_of(answer):
    """Informative sentences of an answer, without citation markers or courtesy lines."""
    sentences = []
    # Split before dropping markers, so "... tersedia. [S1] menyebut ..." stays two sentences.
    for part in re.split(r"(?<=[.!?])\s+|\n+", answer.strip()):
        part = CITATION.sub("", part).strip()
        if not re.search(r"\w", part):
            continue  # leftover punctuation between markers, e.g. "[S1]–[S10]"
        if sentences and re.search(r"\b[A-Z](?:\.[A-Z])*\.$", sentences[-1]):
            sentences[-1] += " " + part  # abbreviation such as "T.A." does not end a sentence
        elif part:
            sentences.append(part)
    return [s for s in sentences if not COURTESY_SENTENCE.search(s)]


# A marker range over many sources ("[S1]–[S10]", "[S1–S10]") describes the sources as a whole.
WIDE_RANGE = re.compile(r"\[S(\d+)\]\s*[-–—]\s*\[S(\d+)\]|\[S(\d+)\s*[-–—]\s*S(\d+)\]")


def without_source_overviews(answer):
    """Drop sentences supported only by a wide marker range, e.g. "[S1]–[S10] membahas penilaian kinerja,
    bukan prosedur SIM": they summarise what the sources are about instead of citing evidence."""
    kept = []
    for part in re.split(r"(?<=[.!?])\s+|\n+", answer.strip()):
        spans = [[int(n) for n in m.groups() if n] for m in WIDE_RANGE.finditer(part)]
        wide = any(len(n) == 2 and n[1] - n[0] >= 4 for n in spans)
        if wide and not CITATION.search(WIDE_RANGE.sub("", part)):
            continue
        kept.append(part)
    return " ".join(kept)


def is_abstention(answer):
    """True when every sentence only says the information is absent (no factual claim to cite)."""
    informative = sentences_of(without_source_overviews(answer))
    return bool(informative) and all(ABSTAIN_SENTENCE.search(s) for s in informative)


CLARIFY_SENTENCE = re.compile(r"\b(?:perjelas|jelaskan|maksud anda|yang anda maksud)\b", re.I)


def uncited_kind(answer):
    """Classify an answer without citations: 'clarify', 'absent' (only says it is not found) or 'content'."""
    sentences = sentences_of(answer)
    if all(CLARIFY_SENTENCE.search(s) for s in sentences):
        return "clarify"
    if all(ABSENCE_STATEMENT.search(s) or CLARIFY_SENTENCE.search(s) for s in sentences):
        return "absent"
    return "content"


def out_of_scope_message(titles):
    """Friendly fixed reply when the documents do not contain the answer (never generated by the model)."""
    listed = " atau ".join([", ".join(titles[:-1]), titles[-1]]) if len(titles) > 1 else "".join(titles)
    return (
        "Mohon maaf, SIRA belum menemukan informasi tersebut dalam dokumen yang tersedia. "
        "SIRA hanya menjawab berdasarkan isi dokumen knowledge base agar setiap jawaban dapat "
        "dipertanggungjawabkan, sehingga belum dapat membantu pertanyaan di luar dokumen tersebut. "
        + (f"Silakan ajukan pertanyaan seputar {listed}." if listed else "Silakan ajukan pertanyaan lain.")
    )


def reports_absence(answer):
    """True when at least one sentence states that information is missing from the documents."""
    return any(ABSENCE_STATEMENT.search(s) for s in sentences_of(answer))


