# A chunk ending with a printed catchword ("1) Ijazah .....") continues on the next page.
CONTINUES = re.compile(r"(?:\.{3,}|…)\s*$")


def redraft(shown, message):
    """Clear a visible draft, or only update the status when nothing was shown yet."""
    return event("reset_answer", message=message) if shown else event("status", message=message)


def event(kind, **values):
    return "data: " + json.dumps({"type": kind, **values}, ensure_ascii=False) + "\n\n"


@dataclass
class Session:
    updated: float
    revision: int
    token_hash: str
    questions: list[str] = field(default_factory=list)
    search_context: str = ""
    lock: asyncio.Lock = field(default_factory=asyncio.Lock)


class Chat:
    def __init__(self, settings, db, vectors, relay):
        self.settings, self.db, self.vectors, self.relay = settings, db, vectors, relay
        self.sessions = {}
        self.cache_lock = RLock()
        self.lexical = LexicalIndex(db)

    def _cache(self, token, session):
        now = time.monotonic()
        self.sessions = {
            key: value
            for key, value in self.sessions.items()
            if value.lock.locked() or now - value.updated < self.settings.session_cache_ttl
        }
        if len(self.sessions) >= 100:
            idle = [key for key, value in self.sessions.items() if not value.lock.locked()]
            if not idle:
                raise AIError("Terlalu banyak percakapan sedang menjawab. Silakan coba beberapa saat lagi.")
            del self.sessions[min(idle, key=lambda key: self.sessions[key].updated)]
        self.sessions[token] = session

    def create(self, previous_token=None):
        with self.cache_lock:
            token = secrets.token_urlsafe(32)
            session = Session(time.monotonic(), self.db.revision, digest(token))
            with self.db.connect() as conn:
                if previous_token:
                    conn.execute("DELETE FROM chat_sessions WHERE token_hash=?", (digest(previous_token),))
                conn.execute(
                    "INSERT INTO chat_sessions(token_hash,revision,updated) VALUES (?,?,?)",
                    (session.token_hash, session.revision, time.time()),
                )
            if previous_token:
                self.sessions.pop(previous_token, None)
            self._cache(token, session)
            return token

    def get(self, token):
        with self.cache_lock:
            row = self.db.one("SELECT * FROM chat_sessions WHERE token_hash=?", (digest(token),))
            if not row:
                self.sessions.pop(token, None)
                return None
            session = self.sessions.get(token)
            if session is None:
                session = Session(
                    time.monotonic(),
                    row["revision"],
                    row["token_hash"],
                    json.loads(row["questions"]),
                    row["search_context"],
                )
                self._cache(token, session)
            session.updated = time.monotonic()
            return session

    def history(self, session):
        return [
            json.loads(row["content"])
            for row in self.db.rows(
                "SELECT content FROM chat_messages WHERE session_hash=? ORDER BY id", (session.token_hash,)
            )
        ]

    def _save_session(self, session):
        self.db.execute(
            "UPDATE chat_sessions SET revision=?,questions=?,search_context=?,updated=? WHERE token_hash=?",
            (session.revision, json.dumps(session.questions), session.search_context, time.time(), session.token_hash),
        )

    def titles(self):
        return [
            row["title"]
            for row in self.db.rows(
                "SELECT title FROM documents WHERE deleted=0 AND active_version IS NOT NULL ORDER BY created"
            )
        ]

    def needs_rewrite(self, question, session):
        """Only messages that a plain search would likely misread go through the model first:
        follow-ups, page references, very short messages, or words absent from the documents."""
        if session.questions and (FOLLOW_UP.match(question) or FOLLOW_UP_REFERENCE.search(question)):
            return True
        if page_numbers(question) or len(terms(question)) < 3:
            return True
        return bool(self.lexical.unknown_terms(question))

    def rewrite(self, question, session):
        """Search query written by the model from the user's wording. Falls back to None on any failure."""
        rewrite = getattr(self.relay, "rewrite", None)
        if rewrite is None or not self.needs_rewrite(question, session):
            return None
        documents = self.db.rows(
            "SELECT id,title FROM documents WHERE deleted=0 AND active_version IS NOT NULL ORDER BY created"
        )
        try:
            result = rewrite(question, session.questions[-4:], [row["title"][:180] for row in documents][:50])
        except AIError as exc:
            log.info("rewrite_skipped reason=%s", type(exc).__name__)
            return None
        query = " ".join(result["query"].split())[:1500]
        if not query:
            return None
        document = next((row["id"] for row in documents if row["title"] == result["document"].strip()), None)
        pages = sorted({page for page in result["pages"] if 1 <= page <= 1000})[:6]
        return query, {"document_id": document, "pages": pages}

    def chunk_row(self, where, params):
        return self.db.one(
            """SELECT c.*,d.title,d.id AS document_id FROM chunks c JOIN documents d
            ON d.active_version=c.version_id WHERE d.deleted=0 AND """
            + where
            + " ORDER BY c.id LIMIT 1",
            params,
        )

    def with_continuations(self, selected, max_sources=10, top=2):
        """Add the next page's first chunk after one of the top chunks that visibly continues there.

        Only the strongest sources are extended (announcements often end every page with a catchword),
        so continuations never push other relevant evidence out of the source limit.
        """
        result, seen = [], {s["id"] for s in selected}
        for index, source in enumerate(selected):
            result.append(source)
            if index < top and CONTINUES.search(source["text"]):
                following = self.chunk_row("c.version_id=? AND c.page=?", (source["version_id"], source["page"] + 1))
                if following and following["id"] not in seen:
                    seen.add(following["id"])
                    result.append(following)
        return [dict(row, source_id=f"S{index}") for index, row in enumerate(result[:max_sources], 1)]

    def retrieve(self, query, hints=None, original=None):
        versions = self.db.active_versions()
        if not versions:
            return []
        started = time.monotonic()
        # With a rewritten query, the user's own wording is searched too (one embedding batch), so a
        # rewrite can add evidence but never removes what the original question would have found.
        queries = [query] + ([original] if original and original != query else [])
        embeddings = self.relay.embed(queries)
        embedded = time.monotonic()
        best = {}
        for embedding in embeddings:
            for chunk_id, distance in self.vectors.search(embedding, versions, limit=36):
                best[chunk_id] = min(distance, best.get(chunk_id, distance))
        candidates = sorted(best.items(), key=lambda item: (item[1], item[0]))
        found = []
        for chunk_id, distance in candidates:
            if distance > 0.85:
                continue
            row = self.db.one(
                """SELECT c.*,d.title,d.id AS document_id FROM chunks c JOIN documents d
                ON d.active_version=c.version_id WHERE c.id=? AND d.deleted=0""",
                (chunk_id,),
            )
            if row:
                row["distance"] = distance
                found.append(row)
        hints = hints or {}
        page_document = hints.get("document_id")
        pages = hints.get("pages") or page_numbers(query)
        scored = {}
        for text in queries:
            for row, score in self.lexical.search(text, pages=pages, page_document=page_document):
                if score > scored.get(row["id"], (None, -1))[1]:
                    scored[row["id"]] = (row, score)
        lexical = sorted(scored.values(), key=lambda item: (-item[1], item[0]["id"]))[:20]
        documents, focused = self.lexical.cross_document(query)
        if page_document and pages:
            # Pages the user names explicitly in the document under discussion are always sent.
            focused = [
                row for page in pages[:3] if (row := self.chunk_row("d.id=? AND c.page=?", (page_document, page)))
            ] + focused
        selected = self.with_continuations(fuse(found, lexical, focused=focused, documents=documents))
        log.info(
            "retrieval embedding_ms=%s retrieval_ms=%s semantic=%s lexical=%s sources=%s",
            round((embedded - started) * 1000),
            round((time.monotonic() - embedded) * 1000),
            len(found),
            len(lexical),
            [(s["source_id"], s["document_id"], s["page"], s["id"]) for s in selected],
        )
        return selected

    async def stream(self, session, question):
        async with session.lock:
            if not self.db.one("SELECT 1 FROM chat_sessions WHERE token_hash=?", (session.token_hash,)):
                yield event("error", message="Percakapan sudah diganti. Silakan muat ulang halaman.")
                return
            assistant = {"role": "assistant", "text": "", "sources": [], "pending": True}
            with self.db.connect() as conn:
                conn.execute(
                    "INSERT INTO chat_messages(session_hash,content) VALUES (?,?)",
                    (
                        session.token_hash,
                        json.dumps({"role": "user", "text": question}),
                    ),
                )
                message_id = conn.execute(
                    "INSERT INTO chat_messages(session_hash,content) VALUES (?,?)",
                    (
                        session.token_hash,
                        json.dumps(assistant),
                    ),
                ).lastrowid
            last_saved = 0.0

            def save():
                self.db.execute("UPDATE chat_messages SET content=? WHERE id=?", (json.dumps(assistant), message_id))

            try:
                async for packet in self._answer_stream(session, question):
                    value = json.loads(packet.removeprefix("data: "))
                    kind = value["type"]
                    if kind == "delta":
                        assistant["text"] += value["text"]
                    elif kind == "notice":
                        assistant["notice"] = value["message"]
                    elif kind == "replace_answer":
                        assistant["text"] = value["text"]
                    elif kind == "reset_answer":
                        assistant.update(text="", sources=[])
                    elif kind == "done":
                        assistant.update(sources=value["sources"], pending=False)
                        self._save_session(session)
                    elif kind == "error":
                        assistant.update(error=value["message"], pending=False)
                    if kind != "status" and (kind != "delta" or time.monotonic() - last_saved >= 0.5):
                        save()
                        last_saved = time.monotonic()
                    yield packet
            finally:
                if assistant["pending"]:
                    assistant.update(
                        pending=False, error="Jawaban terputus sebelum selesai. Silakan kirim ulang pertanyaan."
                    )
                save()
                self._save_session(session)

    async def _answer_stream(self, session, question):
        started = time.monotonic()
        session.updated = time.monotonic()
        revision = self.db.revision
        if session.revision != revision:
            session.questions.clear()
            session.search_context = ""
            session.revision = revision
            yield event(
                "notice",
                message="Knowledge base telah berubah; konteks sebelumnya direset agar sumber lama tidak digunakan.",
            )
        # Only complete, allowlisted social messages take this fixed-response path.
        # Extra questions or instructions still pass through retrieval and relay policy.
        # These replies work with an empty KB and never replace the document topic.
        social_reply = IDENTITY_REPLY if IDENTITY.fullmatch(question) else None
        if social_reply is None and GREETING.fullmatch(question):
            social_reply = GREETING_REPLY
        if social_reply:
            yield event("delta", text=social_reply)
            yield event("done", sources=[])
            return
        if not self.db.active_versions():
            yield event(
                "delta",
                text="Saat ini belum ada dokumen yang tersedia. Silakan hubungi admin untuk menambahkan knowledge base.",
            )
            yield event("done", sources=[])
            return
        follow_up = bool(FOLLOW_UP.match(question) or FOLLOW_UP_REFERENCE.search(question)) and len(question) < 180
        if FOLLOW_UP.match(question) and not session.questions:
            yield event(
                "delta",
                text="Mohon jelaskan topik atau ketentuan yang Anda maksud agar saya dapat mencari informasi yang sesuai.",
            )
            yield event("done", sources=[])
            return
        query, hints = question, None
        try:
            yield event("status", message="Mencari informasi dalam dokumen...")
            # The model turns slang, typos and follow-ups into a clean search query; the user's own
            # wording still goes to the answer step. Without the relay rewrite, use local rules.
            rewritten = await asyncio.to_thread(self.rewrite, question, session)
            if rewritten:
                query, hints = rewritten
            elif follow_up and session.questions:
                query = session.search_context[-1400:] + "\nPertanyaan lanjutan: " + question
            sources = await (
                asyncio.to_thread(self.retrieve, query, hints, question)
                if hints
                else asyncio.to_thread(self.retrieve, query)
            )
            if self.db.revision != revision:
                raise AIError("Knowledge base berubah saat pencarian. Silakan kirim ulang pertanyaan.")
            if not sources:
                yield event("delta", text=out_of_scope_message(self.titles()))
                yield event("done", sources=[])
                return
            payload = {
                "question": question,
                "history": session.questions[-4:],
                "sources": [
                    {"id": s["source_id"], "title": s["title"], "page": s["page"], "text": s["text"]} for s in sources
                ],
            }
            first = True
            yield event("status", message="Menyusun jawaban berdasarkan sumber...")
            citation_retried = False
            evidence_checked = False
            fallback = False
            valid = {s["source_id"] for s in sources}
            for _ in range(3):
                answer = ""
                # Text stays hidden until it cites a valid source. An uncited draft (possibly general
                # knowledge) is checked first and never flashes on screen before being replaced.
                shown = False
                async for text in self.relay.answer(payload):
                    if self.db.revision != revision:
                        raise AIError(
                            "Knowledge base berubah. Jawaban ini belum selesai; silakan kirim ulang pertanyaan."
                        )
                    if first:
                        log.info("chat_first_text_ms=%s", round((time.monotonic() - started) * 1000))
                        first = False
                    answer += text
                    if shown:
                        yield event("delta", text=text)
                    elif cited_ids(answer, valid) & valid and not is_abstention(answer):
                        # A cited "not found" sentence is still held: it becomes the friendly reply.
                        shown = True
                        log.info("chat_first_visible_ms=%s", round((time.monotonic() - started) * 1000))
                        yield event("delta", text=answer)
                cited = cited_ids(answer, valid)
                if cited - valid:
                    raise AIError("Referensi jawaban tidak valid. Silakan coba kembali.")
                if answer.strip() != SAFE_REFUSAL and not evidence_checked and reports_absence(answer):
                    evidence_checked = True
                    additional = await asyncio.to_thread(self.retrieve, verification_query(query, question))
                    if self.db.revision != revision:
                        raise AIError("Knowledge base berubah saat pencarian. Silakan kirim ulang pertanyaan.")
                    old_ids = {s["id"] for s in sources}
                    new_evidence = [s for s in additional if s["id"] not in old_ids]
                    if new_evidence:
                        # Keep prior evidence, but ensure newly discovered sources are included.
                        sources = fuse(new_evidence[:3] + sources, [])
                        valid = {s["source_id"] for s in sources}
                        payload["sources"] = [
                            {"id": s["source_id"], "title": s["title"], "page": s["page"], "text": s["text"]}
                            for s in sources
                        ]
                        yield redraft(shown, "Memeriksa sumber tambahan...")
                        continue
                # Without citations only a refusal, "not found" or clarification may pass. Any other
                # sentence (for example general knowledge followed by a disclaimer) needs sources.
                missing = not cited and answer.strip() != SAFE_REFUSAL and uncited_kind(answer) == "content"
                if not missing:
                    break
                if citation_retried:
                    fallback = True  # still unsupported: answer with the fixed friendly reply
                    break
                payload["citation_retry"] = True
                citation_retried = True
                yield redraft(shown, "Memeriksa ulang referensi jawaban...")
            if answer.strip() != SAFE_REFUSAL and (
                fallback or (cited and is_abstention(answer)) or (not cited and uncited_kind(answer) == "absent")
            ):
                # "Not found" cites nothing: show one consistent, friendly reply without references.
                answer = out_of_scope_message(self.titles())
                cited = set()
                if shown:
                    # Replace in place, without flashing back to the waiting state.
                    yield event("replace_answer", text=answer)
            if not shown and answer.strip():
                # Checked answer without citations (refusal, not found, clarification): show it whole.
                yield event("delta", text=answer)
            references = [
                {"id": s["source_id"], "title": s["title"], "page": s["page"], "heading": s["heading"]}
                for s in sources
                if s["source_id"] in cited
            ]
            # The model may abstain without citations. Never label such a result as sourced.
            if not answer.strip():
                raise AIError("Layanan AI belum memberikan jawaban. Silakan coba kembali.")
            if answer.strip() == SAFE_REFUSAL:
                # A refused instruction must not replace the legitimate topic
                # or become additional instruction-bearing session history.
                yield event("done", sources=[])
                return
            session.questions = (session.questions + [question])[-4:]
            session.search_context = query[-1800:]
            session.updated = time.monotonic()
            yield event("done", sources=references)
            log.info("chat_complete_ms=%s sources=%s", round((time.monotonic() - started) * 1000), len(references))
        except AIError as exc:
            yield event("error", message=str(exc))
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            log.warning("chat_failed type=%s", type(exc).__name__)
            yield event("error", message="Jawaban belum dapat diselesaikan. Silakan coba kembali.")
